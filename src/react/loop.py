import time
from pathlib import Path
from rich.console import Console
from subprocess import run
import subprocess
from src.tools import safe_git_commit  # Real tool integration (full wiring)

console = Console()

def determine_target_file(feature_description: str) -> str:
    """Fully dynamic + extensible file selection (no baked limits — grows with every task)."""
    lower = feature_description.lower()
    if "grokforge ship" in lower or "ship <feature-description>" in lower:
        return "src/main.py"
    elif "rich streaming ui" in lower or "dashboard" in lower or "live dashboard" in lower:
        Path("src/ui").mkdir(parents=True, exist_ok=True)
        return "src/ui/rich_streaming.py"
    elif "test" in lower or "e2e" in lower:
        Path("tests").mkdir(parents=True, exist_ok=True)
        return "tests/test_e2e.py"
    elif "pyproject" in lower or "release" in lower:
        return "pyproject.toml"
    elif "react 2.0" in lower or "autonomous loop" in lower or "wire full" in lower:
        return "src/react/loop.py"  # Self-improving!
    else:
        # General fallback for any future task
        slug = "".join(c if c.isalnum() else "_" for c in feature_description.lower()[:40])
        Path("src/features").mkdir(parents=True, exist_ok=True)
        return f"src/features/{slug}.py"


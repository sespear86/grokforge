def determine_target_file(feature_description: str) -> str:
    """FULLY DYNAMIC + CONFIG-PROTECTING file selection (v37 — GitHub Actions / CI prioritized BEFORE test to prevent 'testing' mismatch forever)."""
    lower = feature_description.lower()
    if "grokforge ship" in lower or "ship <feature-description>" in lower:
        return "src/main.py"
    elif "rich streaming ui" in lower or "dashboard" in lower or "rich_streaming" in lower:
        Path("src/ui").mkdir(parents=True, exist_ok=True)
        return "src/ui/rich_streaming.py"
    elif "github actions" in lower or "ci" in lower or "workflow" in lower or "automated testing" in lower or "release" in lower:
        Path(".github/workflows").mkdir(parents=True, exist_ok=True)
        return ".github/workflows/grokforge-ci.yml"
    elif "test" in lower or "e2e" in lower:
        Path("tests").mkdir(parents=True, exist_ok=True)
        return "tests/test_e2e.py"
    elif "pyproject" in lower or "release" in lower or "pip" in lower or "toml" in lower:
        return "pyproject.toml"
    elif "systemd" in lower or "service" in lower or "daemon" in lower or "persistent" in lower:
        Path("scripts").mkdir(parents=True, exist_ok=True)
        return "scripts/grokforge.service"
    elif "react 2.0" in lower or "autonomous loop" in lower or "wire full" in lower or "loop.py" in lower:
        return "src/react/loop.py"
    elif "react tool" in lower or "web search" in lower or "code analysis" in lower or "more react" in lower:
        Path("src/tools").mkdir(parents=True, exist_ok=True)
        return "src/tools/web_search.py"
    else:
        slug = "".join(c if c.isalnum() else "_" for c in feature_description.lower()[:40])
        Path("src/features").mkdir(parents=True, exist_ok=True)
        return f"src/features/{slug}.py"

